-- Kopiowanie ścieżki
map("n", "<leader>pa", function()
	local path = vim.fn.expand("%:p")
	vim.fn.setreg("+", path)
	print("Skopiowano ścieżkę:", path)
end, "Skopiuj pełną ścieżkę pliku")

