local function map(mode, key, fn, desc)
	vim.keymap.set(mode, key, fn, { noremap = true, silent = true, desc = desc })
end

-- Podstawowe i systemowe
map("n", "<leader>w", "<cmd>w<CR>", "Zapisz plik")
map("n", "<leader>q", "<cmd>q<CR>", "Wyjdź")
map("n", "<leader>cc", "<cmd>e $MYVIMRC<CR>", "Edytuj konfigurację Neovim")
map("i", "<C-s>", "<cmd>write<CR><Esc>", "Zapisz plik (Insert mode)")
vim.api.nvim_create_user_command("W", "w", {})

-- Nawigacja i edycja
vim.keymap.set("n", "j", function()
	return vim.v.count == 0 and "gj" or "j"
end, { expr = true, silent = true, desc = "Down (wrap-aware)" })
vim.keymap.set("n", "k", function()
	return vim.v.count == 0 and "gk" or "k"
end, { expr = true, silent = true, desc = "Up (wrap-aware)" })
