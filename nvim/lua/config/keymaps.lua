map("n", "<leader>cf", function()
	vim.lsp.buf.code_action({ context = { only = { "source.organizeImports" }, diagnostics = {} }, apply = true })
	vim.defer_fn(function()
		vim.lsp.buf.format({})
	end, 50)
end, "Organizuj importy i formatuj")
